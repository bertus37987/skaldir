#!/usr/bin/env python3
"""Render the CLI logo art (ANSI) into a pixel-exact PNG, embedded as base64.

The empty-state branding must use the EXISTING CLI logo (`~/gods-voice-cli-logo-art.ansi`)
— not a re-invention. The art is 24-bit-colored half/full block characters
(U+2580 / U+2588 / U+2584), i.e. two vertical pixels per cell, so it renders
exactly as pixel art. No third-party deps: a minimal RGBA PNG writer (zlib).

Output: integrations/hermes/godsv_plugin/desktop/logo_art.js with
  export const LOGO_ART_B64 = "<png base64>"
and prints width/height/bytes for the record.
"""
from __future__ import annotations

import base64
import re
import struct
import zlib
from pathlib import Path

SRC = Path.home() / "gods-voice-cli-logo-art.ansi"
OUT = Path("integrations/hermes/godsv_plugin/desktop/logo_art.js")

SGR = re.compile(r"\x1b\[([0-9;]*)m")
UPPER, FULL, LOWER = "\u2580", "\u2588", "\u2584"


def parse(path: Path):
    rows: list[list[tuple[tuple[int, int, int, int], tuple[int, int, int, int]]]] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        fg: tuple[int, int, int, int] = (0, 0, 0, 0)
        bg: tuple[int, int, int, int] = (0, 0, 0, 0)
        cells = []
        i = 0
        while i < len(raw):
            match = SGR.match(raw, i)
            if match:
                codes = [c for c in match.group(1).split(";") if c]
                if not codes or codes == ["0"]:
                    fg = bg = (0, 0, 0, 0)
                elif len(codes) == 5 and codes[0] == "38":
                    fg = (int(codes[2]), int(codes[3]), int(codes[4]), 255)
                elif len(codes) == 5 and codes[0] == "48":
                    bg = (int(codes[2]), int(codes[3]), int(codes[4]), 255)
                i = match.end()
                continue
            ch = raw[i]
            i += 1
            if ch == UPPER:
                cells.append((fg, bg))
            elif ch == FULL:
                cells.append((fg, fg))
            elif ch == LOWER:
                cells.append((bg, fg))
            else:  # space / unknown -> background only
                cells.append((bg, bg))
        rows.append(cells)
    return rows


def to_pixels(rows) -> tuple[int, int, bytearray]:
    width = max((len(r) for r in rows), default=0)
    height = 2 * len(rows)
    pixels = bytearray()
    for row in rows:
        top = bytearray()
        bottom = bytearray()
        for x in range(width):
            t, b = row[x] if x < len(row) else ((0, 0, 0, 0), (0, 0, 0, 0))
            top += bytes(t)
            bottom += bytes(b)
        pixels += b"\x00" + top      # filter 0 per scanline
        pixels += b"\x00" + bottom
    return width, height, pixels


def png(width: int, height: int, raw: bytes | bytearray) -> bytes:
    def chunk(tag: bytes, data: bytes) -> bytes:
        payload = tag + data
        return struct.pack(">I", len(data)) + payload + struct.pack(">I", zlib.crc32(payload))

    header = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", header)
        + chunk(b"IDAT", zlib.compress(bytes(raw), 9))
        + chunk(b"IEND", b"")
    )


def main() -> None:
    rows = parse(SRC)
    width, height, raw = to_pixels(rows)
    data = png(width, height, raw)
    b64 = base64.b64encode(data).decode("ascii")
    OUT.write_text(
        "/** The CLI logo art (gods-voice-cli-logo-art.ansi) rendered pixel-exact\n"
        " *  as PNG. Generated by tools/render_logo_art.py — do not edit by hand. */\n"
        f"export const LOGO_ART_B64 = '{b64}'\n"
        f"export const LOGO_ART_SIZE = [{width}, {height}]\n",
        encoding="utf-8",
    )
    print(f"logo: {width}x{height}px, png {len(data)} bytes, base64 {len(b64)} chars -> {OUT}")


if __name__ == "__main__":
    main()
